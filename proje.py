import pandas as pd
import matplotlib.pyplot as plt
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split

df = pd.read_csv("gunler.csv", sep=";")

df.head()

print(df.head())

print(df.shape)

print("Satır,Sütun",df.shape)

print(df.groupby("yagmur")[["sicaklik","nem","rüzgar"]].mean().round(1))

plt.scatter(df["nem"],df['sicaklik'],c=df['yagmur'],cmap="viridis")
plt.xlabel("Nem")
plt.ylabel("Sıcaklık")
plt.title("Hava Durumu: Sıcaklık ve Nem")
plt.colorbar(label="Yağdı (1) / Yağmadı (0)")
plt.show()

x = df[["sicaklik","nem","rüzgar"]].values
y = df['yagmur'].values
print(y)

x_egitim, x_test, y_egitim, y_test = train_test_split(x,y,test_size=0.25,random_state=42)

print("Eğitim", x_egitim.shape, "Test" , x_egitim.shape)

model = DecisionTreeClassifier()
model.fit(x_egitim,y_egitim)

tahmin = model.predict(x_test)
dogruluk = accuracy_score(y_test,tahmin)
print("Test doğruluğu" , dogruluk)

def tahmin_et(sicaklik,nem,rüzgar):
  sonuc = model.predict([[sicaklik,nem,rüzgar]])
  return "Yağar" if sonuc == 1 else "Yağmur yok"

